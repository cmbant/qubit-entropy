"""Generate code/critical_side_jets.py: closed forms (sympy) of the chart vectors and their derivatives.

For (P,Q) and a sign sg=+-1:  r=(sg,P,Q)/N, f=(P,-sg,0)/n, g=r x f,  N=sqrt(1+P^2+Q^2), n=sqrt(1+P^2).
The nine components (r_1..3, f_1..3, g_1..3) with their derivatives are produced in three variants:
side_jets0 (values), side_jets1 (values, P- and Q-derivatives), side_jets2 (adds the three second derivatives).
Every returned list is ordered component-major with 1, 3 or 6 entries per component:
(v), (v,d_P,d_Q), (v,d_P,d_Q,d_PP,d_PQ,d_QQ).  The generated functions use only + - * / and the passed sqrt.
"""
import re
import sympy as sp
P, Q, sg = sp.symbols('P Q sg')
N = sp.sqrt(1+P**2+Q**2)
n = sp.sqrt(1+P**2)
r = sp.Matrix([sg, P, Q])/N
f = sp.Matrix([P, -sg, 0])/n
g = r.cross(f)
comps = [sp.simplify(c) for c in list(r)+list(f)+list(g)]


def make(order, name):
    ex = []
    for c in comps:
        ex.append(c)
        if order >= 1:
            ex += [sp.diff(c, P), sp.diff(c, Q)]
        if order >= 2:
            ex += [sp.diff(c, P, 2), sp.diff(c, P, Q), sp.diff(c, Q, 2)]
    rep, red = sp.cse(ex, optimizations='basic')
    lines = ['def %s(P, Q, sg, sqrt):' % name, '    out = [None]*%d' % len(ex)]
    for s_, e in rep:
        lines.append('    %s = %s' % (s_, sp.pycode(e).replace('math.sqrt', 'sqrt')))
    for i, e in enumerate(red):
        lines.append('    out[%d] = %s' % (i, sp.pycode(e).replace('math.sqrt', 'sqrt')))
    lines.append('    return out')
    src = '\n'.join(lines)
    def halfpow(m):
        x, k = m.group(1), int(m.group(2))
        e = (abs(k)-1)//2
        body = '*'.join([x]*e+['sqrt(%s)' % x])
        return '(%s)' % (body if k > 0 else '1/(%s)' % body)
    src = re.sub(r'(\w+)\*\*\((-?\d+)/2\)', halfpow, src)
    assert '**(' not in src, src
    return src


header = '"""Generated by gen_critical_side_jets.py (sympy, common subexpression elimination); do not edit."""\n'
open('critical_side_jets.py', 'w').write(header+'\n\n'.join(make(o, 'side_jets%d' % o) for o in (0, 1, 2))+'\n')
